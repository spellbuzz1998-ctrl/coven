interface Props {
  links: SocialLinks
  className?: string
  size?: number
}

// Renders a row of clickable social icons. Nothing renders if no links are set.
export default function SocialIcons({ links, className = '', size = 20 }: Props) {
  if (!links.length) return null
  return (
    <div className={`flex items-center gap-4 ${className}`}>
      {links.map(s => (
        <a
          key={s.key}
          href={s.href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={s.label}
          title={s.label}
          className="transition-opacity hover:opacity-70"
        >
          <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
            {ICONS[s.key]}
          </svg>
        </a>
      ))}
    </div>
  )
}
